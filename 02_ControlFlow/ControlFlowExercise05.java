public class ControlFlowExercise05 {
    public static void main(String[] args){
        int number = 8;
        if(number % 2 == 0){
            System.out.println("Even");
        }else {
            System.out.println("Odd");
        }
        if (number > 0){
            System.out.println("Positive");
        }else if (number < 0){
            System.out.println("Negative");
        }else {
            System.out.println("Zero");
        }
        number = 1;
        if(number % 2 == 0){
            System.out.println("Even");
        }else {
            System.out.println("Odd");
        }
        if (number > 0){
            System.out.println("Positive");
        }else if (number < 0){
            System.out.println("Negative");
        }else {
            System.out.println("Zero");
        }
        number = 0;
        if(number % 2 == 0){
            System.out.println("Even");
        }else {
            System.out.println("Odd");
        }
        if (number > 0){
            System.out.println("Positive");
        }else if (number < 0){
            System.out.println("Negative");
        }else {
            System.out.println("Zero");
        }
        number = -1;
        if(number % 2 == 0){
            System.out.println("Even");
        }else {
            System.out.println("Odd");
        }
        if (number > 0){
            System.out.println("Positive");
        }else if (number < 0){
            System.out.println("Negative");
        }else {
            System.out.println("Zero");
        }
        number = -2;
        if(number % 2 == 0){
            System.out.println("Even");
        }else {
            System.out.println("Odd");
        }
        if (number > 0){
            System.out.println("Positive");
        }else if (number < 0){
            System.out.println("Negative");
        }else {
            System.out.println("Zero");
        }
    }
}